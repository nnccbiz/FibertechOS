export interface TermsSection { title: string; clauses: { num: number; text: string }[] }

/** The addon section, numbered to continue the quote's existing clauses. */
export function buildFieldWorksSection(startNum: number): TermsSection {
  const endNum = startNum + FIELD_WORKS_CLAUSES.length - 1;
  return {
    title: `${FIELD_WORKS_TITLE} | סעיפים ${startNum} עד ${endNum}`,
    clauses: FIELD_WORKS_CLAUSES.map((text, i) => ({ num: startNum + i, text })),
  };
}

export function hasFieldWorksSection(sections: any): boolean {
  return Array.isArray(sections) && sections.some((s: any) => (s?.title || '').startsWith(FIELD_WORKS_TITLE));
}
